/**
 * 캐릭터 조건부 주의: z04-sigillum·reminiscence-fleurdelys는 원래 게임 내에서 "OO가 메인 슬롯에
 * 장착 시"처럼 특정 캐릭터 이름이 박혀 있는 효과입니다. bonuses는 누구나 받는 기본 보너스이고,
 * characterBonus는 { characterIds, bonuses } 형태로 특정 캐릭터(최대 2명)가 장착했을 때만 추가로
 * 붙는 보너스입니다 — 예를 들어 reminiscence-fleurdelys는 기류 피해 10%가 기본이고, 방랑자 · 기류
 * 혹은 카르티시아가 장착하면 기류 피해 10%가 더 붙어 총 20%가 됩니다. characterBonus가 없으면
 * (null) 캐릭터 조건 없는 기본 보너스만 있는 것입니다.
 *
 * @param {string} id 카탈로그 키(아이콘 파일명으로도 그대로 씀: /main-echoes/{id}.png)
 * @param {string} name 표시 이름
 * @param {string} description 에코 스킬(적에게 입히는 피해) 설명
 * @param {string} passiveDescription 메인 슬롯 장착 시 얻는 전투 보너스 설명
 * @param {[string, number][]} bonuses 누구나 받는 기본 % 보너스 [카테고리, 값] 목록(없으면 빈 배열)
 * @param {{ characterIds: string[], bonuses: [string, number][] }|null} [characterBonus] 특정
 *   캐릭터(최대 2명)가 장착했을 때만 bonuses에 추가로 더해지는 보너스. 없으면 null.
 * @param {Record<string, string>|null} [characterDescriptions] 캐릭터 id별로 description을
 *   완전히 대체하는 문구(예: 루시가 장착하면 전용 효과 문구, 레베카가 장착하면 다른 전용 효과
 *   문구). 장착 캐릭터에 따라 에코 어빌리티 자체가 바뀌는 메인 에코에 씁니다. 없으면 null(항상
 *   description 그대로).
 */
function defineMainEcho(
  id,
  name,
  description,
  passiveDescription = null,
  bonuses = null,
  characterBonus = null,
  characterDescriptions = null,
) {
  return [
    id,
    {
      name,
      icon: `/main-echoes/${id}.png`,
      description,
      passiveDescription,
      bonuses: (bonuses ?? []).map(([category, value]) => ({ category, value })),
      ...(characterBonus
        ? {
            characterBonus: {
              characterIds: characterBonus.characterIds,
              bonuses: (characterBonus.bonuses ?? []).map(([category, value]) => ({ category, value })),
            },
          }
        : {}),
      ...(characterDescriptions ? { characterDescriptions } : {}),
    },
  ]
}

