/**
 * 에코 세트 카탈로그입니다. pieces는 세트 개수별 효과를 담는 확장 가능한 구조입니다. 세트마다
 * 몇 단계가 있는지, 몇 세트에서 발동하는지 전부 다릅니다 — 1세트에만 효과가 있는 세트, 3세트에만
 * 있는 세트, 2세트/5세트가 같이 있는 세트, 1세트/3세트가 같이 있는 세트 등 다양합니다. 몇 세트를
 * 착용하든 그 이하 단계 효과는 전부 함께 적용됩니다. 다만 조건부 효과는 계산에는 반영하지 않고
 * 설명 문구로만 보여줍니다 — bonuses가 있는 단계만 계산에 반영됩니다(없으면 문구만 표시).
 *
 * 아이콘은 항상 /echo-sets/{id}.png 경로라 따로 안 받고 id로 자동 생성합니다 — public/echo-sets/
 * 에 그 파일명으로 이미지를 넣어두면 자동으로 연결됩니다.
 *
 * 새 세트를 추가할 때는 defineSet(...) 호출을 목록 맨 위에 추가하세요(최근 추가한 세트를 위에서부터
 * 바로 찾을 수 있도록).
 */

/**
 * @param {string} id 카탈로그 키(아이콘 파일명으로도 그대로 씀: /echo-sets/{id}.png)
 * @param {string} name 표시 이름
 * @param {...[number, string|null, number|null, string]} tiers 세트 단계 목록. 하나면 그 세트에
 *   그 단계 하나만 존재하는 것이고(예: 1세트 전용), 둘 이상이면 각각 다른 단계로 정의됩니다.
 *   각 항목은 [세트 개수, 카테고리, 값(%), 설명] 튜플입니다. 카테고리는 StatsPage의 합산 스탯
 *   카테고리 이름과 정확히 같아야 하고(원소별로 나누지 말고 '속성 피해 보너스'처럼 공용 카테고리를
 *   씀), 계산에 반영하지 않는 조건부 효과면 카테고리·값에 null을 넣습니다(설명만 표시됨). 같은
 *   세트 개수를 두 번 이상 정의하면 에러를 던집니다(예: 1세트 효과를 두 번 정의할 수 없음).
 *
 *  defineSet('id', 'name', [tier, 'category', value, 'desc'], [tier2, null, null, 'desc2']),
 */
function defineSet(id, name, ...tiers) {
  const pieces = {}
  for (const [tier, category, value, description] of tiers) {
    if (pieces[tier]) {
      throw new Error(`[echoSets] '${id}' 세트에 ${tier}세트 효과가 중복 정의되었습니다.`)
    }
    pieces[tier] = {
      ...(category ? { bonuses: [{ category, value }] } : {}),
      description,
    }
  }
  return [id, { name, icon: `/echo-sets/${id}.png`, pieces }]
}

