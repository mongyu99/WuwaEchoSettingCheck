-- 버전별 통계용 기록. game_version은 저장 시점에 가장 최근 시작한 메인 배너의 제목입니다(예: 37). character_builds는 저장할 때마다 덮어쓰므로 따로 남깁니다.
-- 한 사용자가 같은 버전에 같은 캐릭터를 여러 번 저장하면 마지막 값 하나만 남아, 통계에 중복으로 잡히지 않습니다.
CREATE TABLE build_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    character_id VARCHAR(50) NOT NULL,
    game_version VARCHAR(255) NOT NULL,
    weapon_id VARCHAR(50),
    main_echo_id VARCHAR(50),
    echo_sets JSONB NOT NULL,
    echoes JSONB NOT NULL,
    saved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_build_snapshots_user_character_version UNIQUE (user_id, character_id, game_version)
);

CREATE INDEX idx_build_snapshots_version_character ON build_snapshots (game_version, character_id);
